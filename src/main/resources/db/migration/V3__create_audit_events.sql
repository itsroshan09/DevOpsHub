
CREATE TABLE audit_events (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              incident_id BIGINT NOT NULL,
                              action VARCHAR(50) NOT NULL,
                              details TEXT NOT NULL,
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_audit_events_incident
                                  FOREIGN KEY (incident_id)
                                      REFERENCES incidents(id)
                                      ON DELETE CASCADE,

                              CONSTRAINT chk_audit_events_action
                                  CHECK (length(trim(action)) > 0),

                              CONSTRAINT chk_audit_events_details
                                  CHECK (length(trim(details)) > 0)
);

CREATE INDEX idx_audit_events_incident_created_at
    ON audit_events(incident_id, created_at, id);
